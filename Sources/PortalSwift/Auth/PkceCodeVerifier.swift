import CryptoKit
import Foundation
import Security

/// The PKCE code verifier (RFC 7636) that binds a Google or Apple sign-in to the device that
/// started it, and the `S256` challenge derived from it.
///
/// `PortalAuth` creates a fresh verifier for every sign-in, sends only its challenge with
/// `GET /oauth/urls`, keeps the verifier in the Keychain (`OAuthVerifierStorage`) and sends it
/// with `POST /oauth/tokens`. The backend stores the challenge with the sign-in and refuses an
/// exchange whose verifier does not hash to it, so a grant can only be redeemed by the install
/// that asked for it.
enum PkceCodeVerifier {
  /// The only transform the backend accepts.
  static let challengeMethod = "S256"

  /// 32 bytes encode to 43 base64url characters, the shortest verifier RFC 7636 §4.1 allows.
  static let byteCount = 32

  /// Fills `count` bytes at `buffer` with secure random bytes and returns the `OSStatus`.
  /// `SecRandomCopyBytes` in production; tests inject a deterministic or failing source.
  typealias RandomBytes = (_ count: Int, _ buffer: UnsafeMutableRawPointer) -> OSStatus

  /// The production byte source: the system CSPRNG.
  static let systemRandomBytes: RandomBytes = { count, buffer in
    SecRandomCopyBytes(kSecRandomDefault, count, buffer)
  }

  /// A new verifier: 32 bytes from the system CSPRNG, base64url-encoded without padding.
  ///
  /// There is deliberately no fallback to a weaker source. A verifier an attacker could guess
  /// binds nothing, so a failing generator fails the sign-in instead.
  ///
  /// - Throws: `PortalAuthError.sessionStorageFailure` naming the `OSStatus` when the generator
  ///   fails. The message never carries any generated bytes.
  static func generate(randomBytes: RandomBytes = PkceCodeVerifier.systemRandomBytes) throws -> String {
    var bytes = [UInt8](repeating: 0, count: Self.byteCount)
    let status = bytes.withUnsafeMutableBytes { buffer -> OSStatus in
      guard let base = buffer.baseAddress else {
        return errSecAllocate
      }
      return randomBytes(buffer.count, base)
    }

    guard status == errSecSuccess else {
      PortalLogger.shared.error("PkceCodeVerifier.generate() - The secure random generator failed with OSStatus \(status).")
      throw PortalAuthError.sessionStorageFailure(message: "A code verifier could not be generated (OSStatus \(status)).")
    }
    return Data(bytes).toBase64Url()
  }

  /// The RFC 7636 §4.1 length bounds the backend enforces.
  private static let verifierLengths = 43 ... 128

  /// `true` for 43 to 128 characters from the RFC 7636 unreserved set `[A-Za-z0-9._~-]`, the
  /// same rule the backend applies to `codeVerifier`.
  static func isWellFormed(_ verifier: String) -> Bool {
    guard self.verifierLengths.contains(verifier.utf8.count) else {
      return false
    }
    return verifier.utf8.allSatisfy { byte in
      switch byte {
      case UInt8(ascii: "A") ... UInt8(ascii: "Z"),
           UInt8(ascii: "a") ... UInt8(ascii: "z"),
           UInt8(ascii: "0") ... UInt8(ascii: "9"),
           UInt8(ascii: "."), UInt8(ascii: "_"), UInt8(ascii: "~"), UInt8(ascii: "-"):
        return true
      default:
        return false
      }
    }
  }

  /// `base64url(SHA-256(verifier))` without padding: the `S256` transform of RFC 7636 §4.2.
  ///
  /// The verifier is ASCII by construction, so its UTF-8 bytes are the ASCII bytes the backend
  /// hashes. The challenge is public by design: it is the only part that travels in a URL.
  static func challenge(for verifier: String) -> String {
    Data(SHA256.hash(data: Data(verifier.utf8))).toBase64Url()
  }
}
